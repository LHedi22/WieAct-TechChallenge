"""Runs the Alembic migrations against a real Postgres (DATABASE_URL); skipped if unreachable."""

import asyncio
from pathlib import Path

import pytest
from alembic.config import Config
from alembic.util import AutogenerateDiffsDetected
from sqlalchemy.ext.asyncio import create_async_engine

from alembic import command
from app.core.config import get_settings

BACKEND = Path(__file__).resolve().parents[1]


async def _reachable(url: str) -> bool:
    engine = create_async_engine(url, connect_args={"timeout": 2})
    try:
        async with engine.connect():
            return True
    except Exception:
        return False
    finally:
        await engine.dispose()


@pytest.fixture
def alembic_cfg() -> Config:
    url = get_settings().DATABASE_URL
    if not asyncio.run(_reachable(url)):
        pytest.skip("Postgres not reachable at DATABASE_URL (docker compose up -d db)")
    cfg = Config(str(BACKEND / "alembic.ini"))
    cfg.attributes["url"] = url
    cfg.attributes["configure_logger"] = False
    return cfg


def test_upgrade_matches_models_and_downgrades(alembic_cfg):
    command.downgrade(alembic_cfg, "base")
    command.upgrade(alembic_cfg, "head")
    try:
        command.check(alembic_cfg)  # the migration must match app/models exactly
    except AutogenerateDiffsDetected as e:
        pytest.fail(f"models and migrations differ: {e}")
    command.downgrade(alembic_cfg, "base")
    command.upgrade(alembic_cfg, "head")
