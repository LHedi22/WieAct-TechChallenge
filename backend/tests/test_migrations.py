"""Runs the Alembic migrations against the Postgres test database; skipped if unreachable."""

import pytest
from alembic.util import AutogenerateDiffsDetected

from alembic import command
from tests.db import alembic_config


def test_upgrade_matches_models_and_downgrades(pg_url):
    cfg = alembic_config(pg_url)
    command.downgrade(cfg, "base")
    command.upgrade(cfg, "head")
    try:
        command.check(cfg)  # the migrations must match app/models exactly
    except AutogenerateDiffsDetected as e:
        pytest.fail(f"models and migrations differ: {e}")
    command.downgrade(cfg, "base")
    command.upgrade(cfg, "head")
